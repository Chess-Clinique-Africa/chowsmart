export async function main() {
  console.log("Seeding ChowSmart database...");

  await clearData();
  console.log("Cleared existing data.");

  const { user } = await seedUsers();
  const cuisines = await seedCuisines();
  const restaurants = await seedRestaurants(cuisines);
  const menuItems = await seedMenuItems(restaurants);
  const breads = await seedBreads();
  const recipes = await seedRecipes(cuisines);
  await seedMenuPlan(user.id, menuItems, breads, recipes);

  const counts = {
    users: await prisma.user.count(),
    cuisines: await prisma.cuisine.count(),
    restaurants: await prisma.restaurant.count(),
    restaurantCuisines: await prisma.restaurantCuisine.count(),
    menuItems: await prisma.menuItem.count(),
    breads: await prisma.bread.count(),
    breadIngredients: await prisma.breadIngredient.count(),
    breadNutrition: await prisma.breadNutrition.count(),
    pairings: await prisma.pairing.count(),
    recipes: await prisma.recipe.count(),
    recipeIngredients: await prisma.recipeIngredient.count(),
    menuPlans: await prisma.menuPlan.count(),
    menuPlanItems: await prisma.menuPlanItem.count(),
  };

  console.log("Seed complete. Counts:");
  for (const [key, value] of Object.entries(counts)) {
    console.log(`  ${key}: ${value}`);
  }

  return counts;
}

