async function seedCuisines() {
  const names = [
    "Nigerian",
    "Italian",
    "Chinese",
    "Indian",
    "American",
    "Mediterranean",
    "Continental",
    "African",
    "Japanese",
  ];

  const cuisines = [];
  for (const name of names) {
    const cuisine = await prisma.cuisine.create({
      data: {
        name,
        slug: name.toLowerCase().replace(/\s+/g, "-"),
      },
    });
    cuisines.push(cuisine);
  }
  return Object.fromEntries(cuisines.map((c) => [c.slug, c]));
}

